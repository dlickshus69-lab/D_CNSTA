"""Refresh internal tables from the apworld."""
import argparse
import json
from pathlib import Path
import re

from generate_check_logic import header
import data

ROOT = Path(__file__).resolve().parents[1]
CLIENT = ROOT/'CrashNST-AP-Client/client'


def outputs():
    ids = [crate['id'] for crate in data.CRATES]
    if len(ids) != len(set(ids)):
        raise ValueError('Duplicate frozen crate IDs')
    if len({(c['level'], data.crate_event(c)) for c in data.CRATES}) != len(ids):
        raise ValueError('Duplicate frozen crate events')
    result = {CLIENT/'check_logic_specs.inc': header()}
    masks = {key: (int(primary, 16), int(extra, 16)) for key, primary, extra in re.findall(
        r'\{"(L\d{3})", (0x[0-9a-f]+), (0x[0-9a-f]+)\}', (CLIENT/'gem_reward_specs.inc').read_text())}
    recipes = ['// Generated by tools/build_apworld.py. Stable item IDs and verified game reward masks.']
    for level in data.LEVELS:
        if not level.key.startswith('L'):
            continue
        events = {event: address for event, _, address in data.checks(level)}
        rewards = [data.ITEMS[data.VANILLA_REWARDS[events[event]]] if event in events else 0
                   for event in ('gem', 'extra_gem', 'relic', 'crystal')]
        bits = [*masks[level.key], 0x2000, 0x200 if 'crystal' in events else 0]
        recipes.append('    {"%s", {%s}, {%s}},' % (level.key, ','.join(hex(v) for v in bits), ','.join(str(v) for v in rewards)))
    result[CLIENT/'collectible_specs.inc'] = '\n'.join(recipes)+'\n'
    crates = ['// Generated from verified counting components by catalogue_crates.py / catalogue_gem_box_routes.py.']
    flying = ['// Generated from reviewed crate identities. Preserve published IDs.']
    for row in data.CRATES:
        encoded = row['position_bits']
        if not re.fullmatch('[0-9a-f]{24}', encoded):
            raise ValueError('Invalid crate position: '+row['name'])
        line = '{'+json.dumps(row['level'])+','+json.dumps(row['name'])+','+str(row['id'])+', {'+','.join('0x'+encoded[i:i+2] for i in range(0,24,2))+'}'
        event = ','+json.dumps(data.crate_event(row))
        crates.append(line+(event if row.get('route_member') or row.get('bonus_member') or row.get('map_member') else '')+'},')
        if row.get('flying'):
            flying.append(line+event+'},')
    result[CLIENT/'crate_specs.inc'] = '\n'.join(crates)+'\n'
    result[CLIENT/'flying_crate_specs.inc'] = '\n'.join(flying)+'\n'
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = outputs()
    for path, text in generated.items():
        if args.check:
            if path.read_text(encoding='utf-8') != text:
                raise ValueError('Stale generated table: '+str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding='utf-8')
    print(('Verified' if args.check else 'Updated')+f' {len(generated)} generated files from the canonical APWorld.')


if __name__ == '__main__':
    main()
