"""generate the client's move fixes from the APWorld's logic (V1.3.46)

Ability Shuffle with relaxed Ability Logic: the moves the current logic expects for each level clear, crystal, secret exit
and box past an obstacle (CLEAR_MOVES, CLEAR_GATES, BONUS_MOVES, BONUS_GATES, the crates' own moves). The client adds them
to a seed's own requirements, so a seed made before a fix doesn't show those checks as available too early.
"""

import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "CrashNST-APWorld/worlds/crash_nst"))
from data import LEVELS, ITEMS, CRATES, checks, crate_event, move_requirements


def header():
    lines = ["// Generated by tools/generate_move_fixes.py. Do not edit by hand!"]
    crates = {}
    for crate in CRATES:
        crates.setdefault(crate["level"], []).append(crate_event(crate))
    for level in LEVELS:
        events = [event for event, _, _ in checks(level) if event in ("clear", "crystal", "secret_exit")]
        events.extend(crates.get(level.key, ()))
        for event in dict.fromkeys(events):
            moves = move_requirements(level, event, True, (), True)
            if moves:
                ids = ", ".join(str(ITEMS[name]) for name in moves)
                lines.append("    {" + json.dumps(level.key) + ", " + json.dumps(event) + ", {" + ids + "}},")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    output = ROOT / "CrashNST-AP-Client/client/move_fix_specs.inc"
    output.write_text(header(), encoding="utf-8")
    print(output)
